def validate(library, original):
    required = ['title','summary','meta','fact','impact','talk','watch','metrics','sources','avoid','trigger','risk']
    for before, after in zip(original, library['scenarios'][:30]):
        for field in ['id','name','fact','impact','talk','watch','avoid','condition']:
            assert before[field] == after[field], (before['id'], field)
    for scene in library['scenarios']:
        assert scene['filter'] in set(FILTERS.values())
        assert set(scene['modules']) == set(MODULE_NAMES)
        for kind, module in scene['modules'].items():
            assert all(module.get(k) for k in required), (scene['id'], kind)
            assert len(module['metrics']) == 2
            assert all('〔' in m['value'] and '〕' in m['value'] for m in module['metrics'])
            assert '〔' in module['fact']
        assert (DIST / scene['file']).is_file()


